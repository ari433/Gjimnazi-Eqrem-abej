/**
 * Two-language support: Albanian (default, at /) and German (at /de).
 * UI strings live here; content translations live on each record as *_de
 * fields and are resolved in the data layer (see lib/content/localize.ts).
 */
export const LOCALES = ["sq", "de"] as const;
export type Locale = (typeof LOCALES)[number];

/** Locale-aware internal link. External/anchor links pass through. */
export function lp(locale: Locale, path: string) {
  if (locale === "sq" || !path.startsWith("/") || path.startsWith("//")) return path;
  return path === "/" ? "/de" : `/de${path}`;
}

/** The same page in the other language. */
export function switchPath(pathname: string, to: Locale) {
  const bare = pathname.replace(/^\/de(?=\/|$)/, "") || "/";
  return to === "de" ? (bare === "/" ? "/de" : `/de${bare}`) : bare;
}

export function localeFromPath(pathname: string): Locale {
  return /^\/de(\/|$)/.test(pathname) ? "de" : "sq";
}

